@concept("a", "a1_concept_sgd_paths")
def a1_sgd_paths():
    """GD, constant-step SGD and decayed SGD on one 2-D least-squares problem."""
    rng = np.random.default_rng(0)
    n = 400
    X = rng.normal(size=(n, 2)) * np.array([1.0, 0.45])
    w_true = np.array([1.2, -0.8])
    y = X @ w_true + rng.normal(scale=0.6, size=n)
    w_star = np.linalg.solve(X.T @ X, X.T @ y)

    def loss(w):
        return np.mean((X @ w - y) ** 2)

    def run(batch, steps, eta0, decay):
        w = np.array([-1.0, 1.4])
        path = [w.copy()]
        for t in range(steps):
            idx = rng.integers(0, n, size=batch) if batch < n else np.arange(n)
            grad = 2 * X[idx].T @ (X[idx] @ w - y[idx]) / len(idx)
            w = w - eta0 / (1 + decay * t) * grad
            path.append(w.copy())
        return np.array(path)

    plotting.use_house_style()
    fig, ax = plt.subplots(figsize=(6.4, 4.6))
    g0, g1 = np.meshgrid(np.linspace(-1.4, 2.4, 160), np.linspace(-2.2, 1.8, 160))
    Z = np.array(
        [[loss(np.array([a, b])) for a, b in zip(r0, r1, strict=False)] for r0, r1 in zip(g0, g1, strict=False)]
    )
    ax.contour(g0, g1, Z, levels=np.quantile(Z, np.linspace(0.01, 0.6, 12)), colors="#cfcfcf", linewidths=0.7)
    for label, path, color in (
        ("full batch, constant step", run(n, 200, 0.05, 0.0), P[0]),
        ("SGD (batch 1), constant step", run(1, 1500, 0.05, 0.0), P[4]),
        ("SGD (batch 1), step decayed as 1/(1+γt)", run(1, 1500, 0.05, 0.02), P[3]),
    ):
        ax.plot(path[:, 0], path[:, 1], color=color, linewidth=0.8, alpha=0.8, label=label)
    ax.plot(*w_star, marker="*", markersize=13, color="black", linestyle="none", label="closed-form optimum $w^\\star$")
    ax.set_xlabel("$w_1$")
    ax.set_ylabel("$w_2$")
    ax.set_title("Same loss, three schedules: noise leaves a ball unless the step shrinks")
    ax.legend(fontsize=7.5, loc="lower left")
    return fig


@concept("a", "a2_concept_tree_vs_forest")
def a2_tree_vs_forest():
    """A deep tree's step function against the average of bootstrapped trees, in 1-D."""
    from parts.a_classical.a2_trees_and_forests import DecisionTree

    rng = np.random.default_rng(3)
    x = np.sort(rng.uniform(0, 1, 80))
    truth = lambda t: np.sin(2 * np.pi * t) + 0.5 * t  # noqa: E731
    y = truth(x) + rng.normal(scale=0.35, size=x.size)
    grid = np.linspace(0, 1, 400)[:, None]

    deep = DecisionTree(criterion="mse", max_depth=10, rng=0).fit(x[:, None], y)
    trees = []
    for b in range(60):
        idx = rng.integers(0, x.size, size=x.size)
        trees.append(DecisionTree(criterion="mse", max_depth=10, rng=b).fit(x[idx, None], y[idx]).predict(grid))
    trees = np.array(trees)

    plotting.use_house_style()
    fig, axes = plt.subplots(1, 2, figsize=(9, 3.6), sharey=True)
    for ax in axes:
        ax.scatter(x, y, s=10, color=GREY, alpha=0.7, label="noisy samples")
        ax.plot(grid, truth(grid[:, 0]), color="black", linewidth=1, linestyle=":", label="true function")
    axes[0].step(grid[:, 0], deep.predict(grid), where="mid", color=P[4], linewidth=1.2, label="one deep tree")
    axes[0].set_title("One deep tree: chases every noisy point", fontsize=10)
    for curve in trees[:12]:
        axes[1].plot(grid[:, 0], curve, color=P[0], alpha=0.12, linewidth=0.8)
    axes[1].plot(grid[:, 0], trees.mean(axis=0), color=P[0], linewidth=1.8, label="average of 60 bootstrap trees")
    axes[1].set_title("Average of 60 bootstrap trees: smoother, not smooth", fontsize=10)
    for ax in axes:
        ax.set_xlabel("x")
        ax.legend(fontsize=7, loc="lower left")
    axes[0].set_ylabel("y")
    fig.tight_layout()
    return fig


@concept("a", "a3_concept_kmeans_vs_pca")
def a3_kmeans_vs_pca():
    """The same points compressed two ways: onto a line, or onto k centroids."""
    from parts.a_classical.a3_kmeans_and_pca import KMeans

    rng = np.random.default_rng(1)
    centres = np.array([[-2.0, -1.0], [0.0, 0.3], [2.2, 1.2]])
    X = np.concatenate([c + rng.normal(scale=0.45, size=(25, 2)) for c in centres])
    mean = X.mean(axis=0)
    _, _, vt = np.linalg.svd(X - mean, full_matrices=False)
    direction = vt[0]
    projected = mean + np.outer((X - mean) @ direction, direction)
    km = KMeans(n_clusters=3, rng=0).fit(X)
    snapped = km.centers_[km.labels_]

    plotting.use_house_style()
    fig, axes = plt.subplots(1, 2, figsize=(9, 3.9), sharex=True, sharey=True)
    for ax, targets, title, color in (
        (
            axes[0],
            projected,
            f"PCA, k=1: project onto the best line  (error {np.mean(((X - projected) ** 2).sum(1)):.2f})",
            P[0],
        ),
        (
            axes[1],
            snapped,
            f"k-means, k=3: snap to the nearest centre  (error {np.mean(((X - snapped) ** 2).sum(1)):.2f})",
            P[1],
        ),
    ):
        for a, b in zip(X, targets, strict=False):
            ax.plot([a[0], b[0]], [a[1], b[1]], color=color, alpha=0.35, linewidth=0.8)
        ax.scatter(X[:, 0], X[:, 1], s=12, color=GREY, zorder=3)
        ax.set_title(title, fontsize=9)
        ax.set_aspect("equal")
    line = mean + np.outer(np.linspace(-4, 4, 2), direction)
    axes[0].plot(line[:, 0], line[:, 1], color=P[0], linewidth=1.6)
    axes[1].scatter(km.centers_[:, 0], km.centers_[:, 1], marker="X", s=90, color=P[1], zorder=4, edgecolor="black")
    fig.suptitle(
        "Both minimise squared reconstruction error; they differ in what a point may be replaced by", fontsize=10
    )
    fig.tight_layout()
    return fig


@concept("a", "a4_concept_boosting_stages")
def a4_boosting_stages():
    """Boosting in 1-D: each round fits a small tree to what is still unexplained."""
    from parts.a_classical.a4_gradient_boosting import GradientBoostingRegressor

    rng = np.random.default_rng(2)
    x = np.sort(rng.uniform(0, 1, 150))
    y = np.sin(3 * np.pi * x) * (1 - x) + 2 * x + rng.normal(scale=0.12, size=x.size)
    model = GradientBoostingRegressor(n_estimators=100, learning_rate=0.3, max_depth=2, min_samples_leaf=3, rng=0).fit(
        x[:, None], y
    )
    grid = np.linspace(0, 1, 400)[:, None]

    plotting.use_house_style()
    fig, axes = plt.subplots(1, 4, figsize=(12, 3.1), sharey=True)
    for ax, rounds in zip(axes, (1, 3, 10, 100), strict=False):
        ax.scatter(x, y, s=7, color=GREY, alpha=0.6)
        ax.plot(grid[:, 0], model.predict(grid, n_estimators=rounds), color=P[0], linewidth=1.6)
        residual = y - model.predict(x[:, None], n_estimators=rounds)
        ax.set_title(
            f"after {rounds} round{'s' if rounds > 1 else ''}\nresidual RMS {np.sqrt(np.mean(residual**2)):.3f}",
            fontsize=9,
        )
        ax.set_xlabel("x")
    axes[0].set_ylabel("y")
    fig.suptitle(
        "Gradient boosting: $F_m = F_{m-1} + \\nu\\,h_m$, each $h_m$ a depth-2 tree fitted to the current residuals",
        fontsize=10,
    )
    fig.tight_layout()
    return fig


