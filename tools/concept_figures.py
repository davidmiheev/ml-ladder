@concept("b", "b1_concept_graph")
def b1_graph():
    """A tiny computation graph, forward values above, gradients below — from B1's engine."""
    from parts.b_deep_learning.b1_autodiff_engine import Value

    w, x, b, y = Value(0.8), Value(1.5), Value(-0.4), Value(1.0)
    wx = w * x
    z = wx + b
    h = z.tanh()
    d = h + (-1.0) * y
    L = d * d
    L.backward()
    nodes = {  # name: (x, y, value)
        "w": (0, 3.0, w),
        "x": (0, 2.0, x),
        "b": (0, 1.0, b),
        "y": (0, 0.0, y),
        "w·x": (2.6, 2.5, wx),
        "z = w·x + b": (5.2, 1.9, z),
        "h = tanh z": (7.8, 1.9, h),
        "d = h − y": (10.4, 1.0, d),
        "L = d²": (13.0, 1.0, L),
    }
    edges = [
        ("w", "w·x"),
        ("x", "w·x"),
        ("w·x", "z = w·x + b"),
        ("b", "z = w·x + b"),
        ("z = w·x + b", "h = tanh z"),
        ("h = tanh z", "d = h − y"),
        ("y", "d = h − y"),
        ("d = h − y", "L = d²"),
    ]
    fig, ax = canvas(12.5, 4.0, (-1.3, 14.3), (-0.8, 3.7))
    for a, c in edges:
        (x0, y0, _), (x1, y1, _) = nodes[a], nodes[c]
        arrow(ax, (x0 + 1.05, y0), (x1 - 1.05, y1), color="#9a9a9a")
    for name, (cx, cy, v) in nodes.items():
        box(
            ax,
            cx,
            cy,
            name,
            w=2.1,
            h=0.62,
            color=P[0] if name in ("w", "b") else None,
            fontsize=8.5,
            sub=f"value {v.data:+.3f}  grad {v.grad:+.3f}",
        )
    ax.text(
        6.5, 3.45, "forward pass: compute every value left → right, and keep them", ha="center", fontsize=9, color=P[0]
    )
    ax.text(
        6.5,
        -0.6,
        "backward pass: one sweep right → left, each node's grad = Σ over consumers (consumer grad × local derivative)",
        ha="center",
        fontsize=9,
        color=P[4],
    )
    fig.suptitle(
        "Reverse-mode autodiff on $L = (\\tanh(wx + b) - y)^2$ — numbers computed by B1's own Value class", fontsize=10
    )
    return fig


