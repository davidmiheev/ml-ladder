"""Explanatory figures for the writeups: what each model *is*, before what it scored.

The rung figures (``tools/writeup_figures.py``) are measurements — curves,
confusion matrices, sweeps — and they are regenerated by rerunning the rungs
over three seeds. The figures here are different in kind: they show the idea a
rung is built on (an unrolled recurrence, a patch grid, a variance ball around
an optimum) so that a reader meets the mechanism before the numbers that test
it. None of them needs a trained model or a GPU, so they live in their own
script and regenerate in seconds:

    uv run python tools/concept_figures.py          # every part
    uv run python tools/concept_figures.py A C      # some parts

Where a figure contains numbers, they are computed here from the same code the
rungs use (A2's tree, A3's k-means, C3's positional encoding, ...) rather than
drawn by hand, so a concept figure cannot quietly disagree with its rung.
Files are written as ``figures/<part>/<rung>_concept_<name>.png``.
"""

