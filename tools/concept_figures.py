@concept("b", "b5_concept_optimizers")
def b5_optimizers():
    """SGD, momentum and Adam on an ill-conditioned valley, 60 steps each."""
    scale = np.array([1.0, 25.0])  # curvature 25x larger along w2

    def grad(w):
        return scale * w

    def run(kind, eta, steps=60):
        w = np.array([-4.5, 1.6])
        m = np.zeros(2)
        v = np.zeros(2)
        path = [w.copy()]
        for t in range(1, steps + 1):
            g = grad(w)
            if kind == "sgd":
                w = w - eta * g
            elif kind == "momentum":
                m = 0.9 * m + g
                w = w - eta * m
            else:
                m = 0.9 * m + 0.1 * g
                v = 0.999 * v + 0.001 * g * g
                w = w - eta * (m / (1 - 0.9**t)) / (np.sqrt(v / (1 - 0.999**t)) + 1e-8)
            path.append(w.copy())
        return np.array(path)

    plotting.use_house_style()
    fig, ax = plt.subplots(figsize=(7.5, 3.8))
    g0, g1 = np.meshgrid(np.linspace(-5, 1.2, 200), np.linspace(-2, 2, 200))
    ax.contour(
        g0,
        g1,
        0.5 * (scale[0] * g0**2 + scale[1] * g1**2),
        levels=[0.1, 0.5, 1.5, 4, 8, 14, 22, 35],
        colors="#d0d0d0",
        linewidths=0.7,
    )
    for kind, eta, color, label in (
        ("sgd", 0.075, P[4], "SGD (step near the stability limit 2/25)"),
        ("momentum", 0.012, P[0], "SGD + momentum β=0.9"),
        ("adam", 0.25, P[3], "Adam"),
    ):
        path = run(kind, eta)
        ax.plot(path[:, 0], path[:, 1], marker=".", markersize=3, linewidth=1, color=color, label=label)
    ax.plot(0, 0, marker="*", markersize=12, color="black", linestyle="none")
    ax.set_xlabel("$w_1$ (shallow direction)")
    ax.set_ylabel("$w_2$ (steep direction)")
    ax.set_title("60 steps on a valley 25× steeper in one direction than the other", fontsize=10)
    ax.legend(fontsize=7.5, loc="lower right")
    return fig


