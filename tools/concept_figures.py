FIGURES = ROOT / "docs" / "writeups" / "figures"
REGISTRY: dict[str, list[tuple[str, Callable[[], plt.Figure]]]] = {}
P = plotting.PALETTE
GREY = "#6b6b6b"
LIGHT = "#f2f2f2"


def concept(part: str, name: str):
    """Register a figure function under ``figures/<part>/<name>.png``."""

    def register(function):
        REGISTRY.setdefault(part, []).append((name, function))
        return function

    return register


# -- drawing helpers -----------------------------------------------------------


def box(ax, x, y, text, *, w=1.6, h=0.55, color=None, fontsize=8.5, sub=None):
    """A rounded block centred at (x, y); ``color`` highlights it."""
    edge = color or GREY
    face = (color + "22") if color else LIGHT
    ax.add_patch(
        FancyBboxPatch(
            (x - w / 2, y - h / 2), w, h, boxstyle="round,pad=0.03", linewidth=1.1, edgecolor=edge, facecolor=face
        )
    )
    ax.text(x, y + (0.08 if sub else 0), text, ha="center", va="center", fontsize=fontsize)
    if sub:
        ax.text(x, y - 0.14, sub, ha="center", va="center", fontsize=6.6, color="#555")


def arrow(
    ax,
    start,
    end,
    *,
    color="#8a8a8a",
    style="-|>",
    lw=1.0,
    ls="-",
    rad=0.0,
    text=None,
    text_offset=(0, 0.12),
    fontsize=7,
):
    ax.add_patch(
        FancyArrowPatch(
            start,
            end,
            arrowstyle=style,
            mutation_scale=10,
            color=color,
            linewidth=lw,
            linestyle=ls,
            connectionstyle=f"arc3,rad={rad}",
        )
    )
    if text:
        mx, my = (start[0] + end[0]) / 2 + text_offset[0], (start[1] + end[1]) / 2 + text_offset[1]
        ax.text(mx, my, text, ha="center", va="center", fontsize=fontsize, color=color)


def canvas(width, height, xlim, ylim):
    fig, ax = plt.subplots(figsize=(width, height))
    ax.set_axis_off()
    ax.grid(False)
    ax.set_xlim(*xlim)
    ax.set_ylim(*ylim)
    return fig, ax


