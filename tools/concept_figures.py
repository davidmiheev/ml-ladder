@concept("b", "b3_concept_bn_dropout")
def b3_bn_dropout():
    """What each layer does to activations: BN re-centres and rescales, dropout zeroes and rescales."""
    rng = np.random.default_rng(0)
    plotting.use_house_style()
    fig, axes = plt.subplots(1, 2, figsize=(10, 3.6))
    raw = rng.normal(3.0, 2.5, size=4000)
    normed = (raw - raw.mean()) / raw.std()
    axes[0].hist(raw, bins=60, alpha=0.6, color=P[4], label="pre-activation, one channel (mean 3, std 2.5)")
    axes[0].hist(normed, bins=60, alpha=0.6, color=P[0], label="after BN: mean 0, std 1 (then γ, β re-learn a scale)")
    axes[0].set_title("BatchNorm: standardise each channel over the batch", fontsize=10)
    axes[0].legend(fontsize=6.8, loc="upper left")
    axes[0].set_xlabel("activation value")
    ax = axes[1]
    ax.set_axis_off()
    ax.set_xlim(-0.5, 3.5)
    ax.set_ylim(-0.6, 5.2)
    ax.set_title("Dropout (p = 0.5): a fresh random half of the units is silenced each step", fontsize=10)
    keep = rng.random((2, 5)) > 0.5
    layers = [5, 5, 5, 3]
    positions = [[(c, 4.5 - r * (4.5 / (n - 1)) if n > 1 else 2.25) for r in range(n)] for c, n in enumerate(layers)]
    for c in range(3):
        for a in positions[c]:
            for b_ in positions[c + 1]:
                dropped = (c in (1, 2) and not keep[c - 1][positions[c].index(a)]) or (
                    c + 1 in (1, 2) and not keep[c][positions[c + 1].index(b_)]
                )
                ax.plot(
                    [a[0], b_[0]],
                    [a[1], b_[1]],
                    color="#dddddd" if dropped else "#9a9a9a",
                    linewidth=0.5 if dropped else 0.8,
                    zorder=1,
                )
    for c, column in enumerate(positions):
        for r, (px, py) in enumerate(column):
            off = c in (1, 2) and not keep[c - 1][r]
            ax.scatter(px, py, s=220, color="white" if off else P[0], edgecolor=GREY, zorder=2)
            if off:
                ax.text(px, py, "×", ha="center", va="center", fontsize=11, color=P[4], zorder=3)
    ax.text(
        1.5,
        -0.45,
        "survivors are scaled by 1/(1−p), so the expected activation is unchanged at test time",
        ha="center",
        fontsize=7.5,
    )
    fig.tight_layout()
    return fig


