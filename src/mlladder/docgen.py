"""Generate ``docs/ladder.md`` from the spec so the doc can never drift."""

from __future__ import annotations

from pathlib import Path

from mlladder import ladder as spec
from mlladder.paths import repo_root

HEADER = """<!-- Generated by `ladder docs` from src/mlladder/ladder.py. Do not edit by hand. -->

# Broader ML — hands-on ladder

Classical ML through generative and geometric deep learning, built from scratch
before reaching for libraries. Each part carries a practical-lab reference; the
last part bridges into ignite-catalog.

Run a rung with `ladder run <id>` (for example `ladder run A1 --help`), and see
progress with `ladder status`.
"""


def render() -> str:
    lines = [HEADER]
    for part in spec.parts():
        lines.append(f"## {part.id}. {part.title}\n")
        if part.note:
            lines.append(f"*{part.note}*\n")
        if part.lab:
            lines.append(f"**Lab:** [{part.lab.text}]({part.lab.url})\n")
        if part.package:
            lines.append(f"Folder: `parts/{part.package}/`\n")
        for item in part.items:
            suffix = ""
            if item.module:
                suffix = f" — `parts/{part.package}/{item.module}.py`"
            lines.append(f"- **{item.id}.** {item.title}{suffix}")
            if item.note:
                lines.append(f"  - {item.note}")
        lines.append("")
    return "\n".join(lines) + "\n"


def write_ladder_doc(destination: Path | None = None) -> Path:
    path = destination or repo_root() / "docs" / "ladder.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render())
    return path


if __name__ == "__main__":
    print(write_ladder_doc())
